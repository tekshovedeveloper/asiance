import sanitizeHtml from 'sanitize-html';

const allowedStyles = {
  '*': {
    'background-color': [/^#[0-9a-f]{3,8}$/i, /^rgba?\([\d\s,.%]+\)$/i],
    color: [/^#[0-9a-f]{3,8}$/i, /^rgba?\([\d\s,.%]+\)$/i],
    'font-size': [/^\d+(?:\.\d+)?(?:px|rem|em|%)$/i],
    'font-style': [/^(?:normal|italic)$/i],
    'font-weight': [/^(?:normal|bold|[1-9]00)$/i],
    margin: [/^[\d\s.%-]+(?:px|rem|em|%|auto)?$/i],
    'margin-bottom': [/^\d+(?:\.\d+)?(?:px|rem|em|%)$/i],
    'margin-left': [/^(?:auto|\d+(?:\.\d+)?(?:px|rem|em|%))$/i],
    'margin-right': [/^(?:auto|\d+(?:\.\d+)?(?:px|rem|em|%))$/i],
    'margin-top': [/^\d+(?:\.\d+)?(?:px|rem|em|%)$/i],
    'max-width': [/^\d+(?:\.\d+)?(?:px|rem|em|%|vw)$/i],
    padding: [/^[\d\s.%-]+(?:px|rem|em|%)?$/i],
    'text-align': [/^(?:left|right|center|justify)$/i],
    'text-decoration': [/^(?:none|underline|line-through)$/i],
    width: [/^\d+(?:\.\d+)?(?:px|rem|em|%|vw)$/i],
  },
};

export function sanitizeArticleHtml(value: string) {
  return sanitizeHtml(value, {
    allowedTags: [
      'p',
      'br',
      'h1',
      'h2',
      'h3',
      'h4',
      'h5',
      'h6',
      'strong',
      'b',
      'em',
      'i',
      'u',
      's',
      'strike',
      'del',
      'ins',
      'blockquote',
      'ul',
      'ol',
      'li',
      'a',
      'img',
      'figure',
      'figcaption',
      'pre',
      'code',
      'hr',
      'span',
      'div',
      'table',
      'thead',
      'tbody',
      'tfoot',
      'tr',
      'th',
      'td',
      'iframe',
    ],
    allowedAttributes: {
      '*': ['class', 'id', 'title', 'style'],
      a: ['href', 'name', 'target', 'rel'],
      img: ['src', 'alt', 'title', 'width', 'height', 'loading'],
      ol: ['start', 'type'],
      td: ['colspan', 'rowspan'],
      th: ['colspan', 'rowspan', 'scope'],
      iframe: ['src', 'width', 'height', 'allow', 'allowfullscreen', 'loading', 'title'],
    },
    allowedSchemes: ['http', 'https', 'mailto', 'tel'],
    allowedStyles,
    allowedIframeHostnames: ['www.youtube.com', 'youtube.com', 'player.vimeo.com'],
    transformTags: {
      a: (tagName, attribs) => ({
        tagName,
        attribs: {
          ...attribs,
          ...(attribs.target === '_blank' ? { rel: 'noopener noreferrer' } : {}),
        },
      }),
      img: (tagName, attribs) => ({
        tagName,
        attribs: {
          ...attribs,
          loading: attribs.loading || 'lazy',
        },
      }),
    },
  });
}
